    subroutine validate_id(value, label)
        character(len=*), intent(in) :: value, label
        if (len_trim(value) == 0) then
            write(*,'(A,A)') 'ERROR: empty identifier: ', trim(label)
            error stop 5
        end if
        if (index(value,'..') /= 0 .or. index(value,'/') /= 0 .or. &
            index(value,achar(92)) /= 0 .or. index(value,':') /= 0) then
            write(*,'(A,A)') 'ERROR: path characters are not allowed in ', trim(label)
            error stop 5
        end if
    end subroutine validate_id


    subroutine validate_fingerprint(value)
        character(len=*), intent(in) :: value
        integer :: idx, code
        if (len_trim(value) /= 32) then
            error stop 'ERROR: case_fingerprint must contain 32 hexadecimal characters.'
        end if
        do idx = 1, len_trim(value)
            code = iachar(value(idx:idx))
            if (.not. ((code >= iachar('0') .and. code <= iachar('9')) .or. &
                       (code >= iachar('a') .and. code <= iachar('f')))) then
                error stop 'ERROR: case_fingerprint is not lowercase hexadecimal.'
            end if
        end do
    end subroutine validate_fingerprint


    subroutine validate_wall_time_settings()
        if (wall_time_limit_s <= 0.0_dp) then
            error stop 'ERROR: wall_time_limit_s must be positive.'
        end if
        if (wall_time_reserve_s < 0.0_dp .or. &
            wall_time_reserve_s >= wall_time_limit_s) then
            error stop &
                'ERROR: wall_time_reserve_s must be nonnegative and smaller than wall_time_limit_s.'
        end if
    end subroutine validate_wall_time_settings


    subroutine make_case_directory_strict(root, campaign, path)
        character(len=*), intent(in) :: root, campaign, path
        character(len=1024) :: parent_path

        parent_path = trim(root)//trim(fold_sep)//trim(campaign)
#ifdef WIN
        command = 'if not exist "'//trim(root)//'" mkdir "'//trim(root)//'"'
        call run_command_checked(command, 'create results root')
        command = 'if not exist "'//trim(parent_path)//'" mkdir "'// &
                  trim(parent_path)//'"'
        call run_command_checked(command, 'create campaign directory')
        command = 'mkdir "'//trim(path)//'"'
#else
        command = 'mkdir -p "'//trim(parent_path)//'"'
        call run_command_checked(command, 'create campaign directory')
        command = 'mkdir "'//trim(path)//'"'
#endif
        call run_command_checked(command, 'create new case directory')
    end subroutine make_case_directory_strict


