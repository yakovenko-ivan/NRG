    subroutine normalize_and_validate_configuration()
        case_id           = adjustl(case_id)
        case_fingerprint  = to_lower_ascii(adjustl(case_fingerprint))
        case_directory    = adjustl(case_directory)
        case_label        = adjustl(case_label)
        campaign_id       = adjustl(campaign_id)
        results_root      = adjustl(results_root)
        numerical_variant = adjustl(numerical_variant)

        coordinate_system = to_lower_ascii(adjustl(coordinate_system))
        mechanism_id      = to_lower_ascii(adjustl(mechanism_id))
        solver_id         = to_lower_ascii(adjustl(solver_id))
        termination_mode  = to_lower_ascii(adjustl(termination_mode))

        if (len_trim(case_directory) == 0) case_directory = case_id
        call validate_id(case_id, 'case_id')
        call validate_fingerprint(case_fingerprint)
        call validate_id(case_directory, 'case_directory')
        call validate_id(campaign_id, 'campaign_id')

        select case(trim(coordinate_system))
        case('cartesian','cylindrical','spherical')
        case default
            error stop &
                "ERROR: coordinate_system must be 'cartesian', 'cylindrical' or 'spherical'."
        end select

        if (domain_length_m <= 0.0_dp .or. cell_size_m <= 0.0_dp) then
            error stop 'ERROR: domain_length_m and cell_size_m must be positive.'
        end if
        if (ignition_width_m <= 0.0_dp .or. ignition_width_m >= domain_length_m) then
            error stop 'ERROR: ignition_width_m must lie in (0, domain_length_m).'
        end if
        if (ignition_temperature <= 0.0_dp) then
            error stop 'ERROR: ignition_temperature must be positive.'
        end if
        if (ignition_h2o_moles <= 0.0_dp .or. ignition_n2_moles <= 0.0_dp) then
            error stop 'ERROR: ignition H2O and N2 mole amounts must be positive.'
        end if

        ratio_check = domain_length_m/cell_size_m
        if (abs(ratio_check-real(nint(ratio_check),dp)) > 1.0e-10_dp) then
            error stop 'ERROR: domain_length_m must be exactly cell-aligned.'
        end if

        ratio_check = ignition_width_m/cell_size_m
        if (abs(ratio_check-real(nint(ratio_check),dp)) > 1.0e-10_dp) then
            error stop 'ERROR: ignition_width_m must be exactly cell-aligned.'
        end if
        if (nint(ratio_check) < 3) then
            error stop 'ERROR: ignition region must span at least three cells.'
        end if

        if (hydrogen_mole_percent <= 0.0_dp .or. &
            hydrogen_mole_percent >= 100.0_dp) then
            error stop 'ERROR: hydrogen_mole_percent must lie in (0,100).'
        end if
        if (n2_o2_molar_ratio <= 0.0_dp) then
            error stop 'ERROR: n2_o2_molar_ratio must be positive.'
        end if
        if (initial_temperature <= 0.0_dp .or. initial_pressure <= 0.0_dp) then
            error stop 'ERROR: initial temperature and pressure must be positive.'
        end if
        if (initial_time_step <= 0.0_dp) then
            error stop 'ERROR: initial_time_step must be positive.'
        end if
        if (cfl_coefficient <= 0.0_dp .or. cfl_coefficient > 1.0_dp) then
            error stop 'ERROR: cfl_coefficient must lie in (0,1].'
        end if
        if (postprocess_interval_ms <= 0.0_dp .or. &
            field_save_interval_ms <= 0.0_dp .or. &
            checkpoint_interval_ms <= 0.0_dp) then
            error stop 'ERROR: all output intervals must be positive.'
        end if

        select case(trim(termination_mode))
        case('simulation_time')
            if (final_time_s <= 0.0_dp) then
                error stop 'ERROR: final_time_s must be positive.'
            end if
        case('wall_time')
            call validate_wall_time_settings()
        case('either')
            if (final_time_s <= 0.0_dp) then
                error stop 'ERROR: final_time_s must be positive.'
            end if
            call validate_wall_time_settings()
        case default
            error stop &
                "ERROR: termination_mode must be 'simulation_time', 'wall_time' or 'either'."
        end select
    end subroutine normalize_and_validate_configuration


    subroutine resolve_mechanism()
        select case(trim(mechanism_id))
        case('keromnes')
            mechanism_name = 'KEROMNES'
        case('konnov')
            mechanism_name = 'KONNOV'
        case('zhang')
            mechanism_name = 'ZHANG'
        case('agafonov','tereza')
            mechanism_name = 'TEREZA'
        case default
            write(*,'(A,A)') 'ERROR: unsupported mechanism_id: ', trim(mechanism_id)
            error stop 3
        end select
        mech_file      = trim(mechanism_name)//'.txt'
        thermo_file    = trim(mechanism_name)//'_THERMO.txt'
        transdata_file = trim(mechanism_name)//'_TRANSDATA.txt'
    end subroutine resolve_mechanism


    subroutine resolve_solver()
        select case(trim(solver_id))
        case('fds','fds_low_mach')
            solver_name = 'fds_low_mach'
        case default
            write(*,'(A,A)') 'ERROR: this campaign interface requires FDS low Mach; got: ', &
                trim(solver_id)
            error stop 4
        end select
    end subroutine resolve_solver


    subroutine validate_id(value, label)
        character(len=*), intent(in) :: value, label
        if (len_trim(value) == 0) then
            write(*,'(A,A)') 'ERROR: empty identifier: ', trim(label)
            error stop 5
        end if
        if (index(value,'..') /= 0 .or. index(value,'/') /= 0 .or. &
            index(value,achar(92)) /= 0 .or. index(value,':') /= 0) then
            write(*,'(A,A)') 'ERROR: path characters are not allowed in ', trim(label)
            error stop 5
        end if
    end subroutine validate_id


    subroutine validate_fingerprint(value)
        character(len=*), intent(in) :: value
        integer :: idx, code

        if (len_trim(value) /= 32) then
            error stop 'ERROR: case_fingerprint must contain 32 hexadecimal characters.'
        end if
        do idx = 1, len_trim(value)
            code = iachar(value(idx:idx))
            if (.not. ((code >= iachar('0') .and. code <= iachar('9')) .or. &
                       (code >= iachar('a') .and. code <= iachar('f')))) then
                error stop 'ERROR: case_fingerprint is not lowercase hexadecimal.'
            end if
        end do
    end subroutine validate_fingerprint


    subroutine validate_wall_time_settings()
        if (wall_time_limit_s <= 0.0_dp) then
            error stop 'ERROR: wall_time_limit_s must be positive.'
        end if
        if (wall_time_reserve_s < 0.0_dp .or. &
            wall_time_reserve_s >= wall_time_limit_s) then
            error stop &
                'ERROR: wall_time_reserve_s must be nonnegative and smaller than wall_time_limit_s.'
        end if
    end subroutine validate_wall_time_settings


