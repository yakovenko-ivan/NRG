!===============================================================================
! AGENTIC 1D WALL / RADIAL FLAME PROPAGATION CAMPAIGN INTERFACE
!===============================================================================
!
! One invocation creates exactly one self-contained NRG case from a namelist
! generated by the 1D campaign generator.
!
! Physical problem:
!   * H2-air mixture at 300 K and 1 atm (campaign defaults)
!   * left boundary: adiabatic slip wall / radial symmetry boundary
!   * right boundary: free outlet to the fresh mixture
!   * ignition zone adjacent to the left boundary
!   * ignition composition: inert H2O + N2 mixture
!   * planar (Cartesian), cylindrical, and spherical 1D geometries
!   * FDS low-Mach solver by default
!   * optional thermal radiation and Soret diffusion
!
! The interface is intentionally deterministic:
!   * one generated namelist -> one logical case;
!   * case identity/fingerprint are supplied by the campaign manifest;
!   * an existing case directory is never overwritten;
!   * species are resolved by name, not mechanism-dependent indices;
!   * run lifetime is delegated to run_control_class;
!   * a lightweight front_history postprocessor is always generated for the
!     external laboratory flame-outcome controller.
!
! The first command-line argument may specify the input namelist. Without an
! argument, setup_input.nml in the current directory is used.
!
! NRG API REQUIREMENTS:
!   This interface targets refactor/core-solvers-validation after the
!   postprocessor subcell/scheduling update and the FDS Soret-propagation fix.
!   front_history therefore records actual CFD sampling times and supports
!   location_mode='quadratic' for subcell extrema.
!===============================================================================

program package_interface

    use, intrinsic :: iso_c_binding, only : c_char, c_int, c_null_char
    use kind_parameters
    use global_data
    use computational_domain_class
    use chemical_properties_class
    use thermophysical_properties_class
    use solver_options_class
    use computational_mesh_class
    use mpi_communications_class
    use data_manager_class
    use boundary_conditions_class
    use field_scalar_class
    use field_vector_class
    use data_save_class
    use data_io_class
    use post_processor_manager_class
    use run_control_class

    implicit none

#ifdef WIN
    interface
        function c_chdir(path) bind(C, name='_chdir') result(status)
            import :: c_char, c_int
            character(kind=c_char), intent(in) :: path(*)
            integer(c_int) :: status
        end function c_chdir
    end interface
#else
    interface
        function c_chdir(path) bind(C, name='chdir') result(status)
            import :: c_char, c_int
            character(kind=c_char), intent(in) :: path(*)
            integer(c_int) :: status
        end function c_chdir
    end interface
#endif

    !--------------------------------------------------------------------------
    ! NRG objects
    !--------------------------------------------------------------------------
    type(computational_domain)                :: problem_domain
    type(data_manager)                        :: problem_data_manager
    type(mpi_communications)                  :: problem_mpi_support
    type(chemical_properties),       target   :: problem_chemistry
    type(thermophysical_properties), target   :: problem_thermophysics
    type(solver_options)                      :: problem_solver_options
    type(computational_mesh),        target   :: problem_mesh
    type(boundary_conditions),       target   :: problem_boundaries
    type(field_scalar_cons),         target   :: p, T, rho
    type(field_vector_cons),         target   :: v, Y
    type(post_processor_manager)              :: problem_post_proc_manager
    type(data_io)                              :: problem_data_io
    type(data_save)                            :: problem_data_save
    type(run_control)                          :: problem_run_control

    !--------------------------------------------------------------------------
    ! Campaign / case identity
    !--------------------------------------------------------------------------
    character(len=32)  :: case_id
    character(len=32)  :: case_fingerprint
    character(len=128) :: case_directory
    character(len=256) :: case_label
    character(len=80)  :: campaign_id
    character(len=256) :: results_root
    character(len=64)  :: numerical_variant

    namelist /case_config/ case_id, case_fingerprint, case_directory, &
        case_label, campaign_id, results_root, numerical_variant

    !--------------------------------------------------------------------------
    ! Geometry
    !--------------------------------------------------------------------------
    character(len=32) :: coordinate_system
    real(dp)          :: domain_length_m
    real(dp)          :: cell_size_m

    namelist /geometry_config/ coordinate_system, domain_length_m, cell_size_m

    !--------------------------------------------------------------------------
    ! Fresh H2-air state
    !--------------------------------------------------------------------------
    real(dp) :: hydrogen_mole_percent
    real(dp) :: n2_o2_molar_ratio
    real(dp) :: initial_temperature
    real(dp) :: initial_pressure

    namelist /mixture_config/ hydrogen_mole_percent, n2_o2_molar_ratio, &
        initial_temperature, initial_pressure

    !--------------------------------------------------------------------------
    ! Ignition region
    !--------------------------------------------------------------------------
    real(dp) :: ignition_temperature
    real(dp) :: ignition_width_m
    real(dp) :: ignition_h2o_moles
    real(dp) :: ignition_n2_moles

    namelist /ignition_config/ ignition_temperature, ignition_width_m, &
        ignition_h2o_moles, ignition_n2_moles

    !--------------------------------------------------------------------------
    ! Physics / numerics
    !--------------------------------------------------------------------------
    character(len=32) :: mechanism_id
    character(len=32) :: solver_id
    logical           :: thermal_radiation_enabled
    logical           :: soret_diffusion_enabled
    real(dp)          :: initial_time_step
    logical           :: cfl_enabled
    real(dp)          :: cfl_coefficient

    namelist /physics_config/ mechanism_id, solver_id, &
        thermal_radiation_enabled, soret_diffusion_enabled, initial_time_step, &
        cfl_enabled, cfl_coefficient

    !--------------------------------------------------------------------------
    ! Run control
    !--------------------------------------------------------------------------
    character(len=24) :: termination_mode
    real(dp)          :: final_time_s
    real(dp)          :: wall_time_limit_s
    real(dp)          :: wall_time_reserve_s

    namelist /run_control_config/ termination_mode, final_time_s, &
        wall_time_limit_s, wall_time_reserve_s

    !--------------------------------------------------------------------------
    ! Output
    !--------------------------------------------------------------------------
    real(dp) :: postprocess_interval_ms
    real(dp) :: field_save_interval_ms
    real(dp) :: checkpoint_interval_ms
    logical  :: save_spatial_fields

    namelist /output_config/ postprocess_interval_ms, &
        field_save_interval_ms, checkpoint_interval_ms, save_spatial_fields

    !--------------------------------------------------------------------------
    ! Derived configuration and local variables
    !--------------------------------------------------------------------------
    character(len=64)   :: mechanism_name
    character(len=64)   :: mech_file
    character(len=64)   :: thermo_file
    character(len=64)   :: transdata_file
    character(len=32)   :: solver_name
    character(len=1024) :: config_file
    character(len=1024) :: work_dir
    character(len=2048) :: command
    character(len=512)  :: iomsg
    character(len=40)   :: h2_field_name

    integer :: io_unit, log_unit, ierr, command_status, exit_status
    integer :: arg_count
    integer :: spec, i
    integer :: h2_index, o2_index, n2_index, h2o_index
    integer :: utter_loop(3,2), inner_loop(3,2)
    integer :: observation_slice(3,2)
    integer :: cells_number_x, ignition_cells
    integer :: ignition_first_cell, ignition_last_cell
    integer :: operations_number

    real(dp) :: nu, phi
    real(dp) :: x_h2, x_o2, x_n2
    real(dp) :: realized_domain_length_m
    real(dp) :: realized_ignition_width_m
    real(dp) :: effective_field_save_interval
    real(dp) :: ratio_check
    logical  :: stop_flag

    !--------------------------------------------------------------------------
    ! Defaults. Campaign files normally override every relevant quantity.
    !--------------------------------------------------------------------------
    case_id                    = 'R000001'
    case_fingerprint           = ''
    case_directory             = 'R000001'
    case_label                 = ''
    campaign_id                = '1D_wall_flame_H2'
    results_root               = '1D_cases'
    numerical_variant          = 'base'

    coordinate_system          = 'cartesian'
    domain_length_m            = 0.1024_dp
    cell_size_m                = 2.0e-4_dp

    hydrogen_mole_percent      = 6.0_dp
    n2_o2_molar_ratio          = 3.762_dp
    initial_temperature        = 300.0_dp
    initial_pressure           = 101325.0_dp

    ignition_temperature       = 3000.0_dp
    ignition_width_m           = 4.8e-3_dp
    ignition_h2o_moles         = 1.0_dp
    ignition_n2_moles          = 1.881_dp

    mechanism_id               = 'keromnes'
    solver_id                  = 'fds_low_mach'
    thermal_radiation_enabled  = .false.
    soret_diffusion_enabled    = .false.
    initial_time_step          = 1.0e-7_dp
    cfl_enabled                = .true.
    cfl_coefficient            = 0.25_dp

    ! External flame-outcome termination normally operates with wall_time mode
    ! and writes run_control.stop when PROPAGATED_OUT/STABILIZED/EXTINGUISHED
    ! is classified. final_time_s remains available for debugging/test runs.
    termination_mode           = 'wall_time'
    final_time_s               = 30.0_dp
    wall_time_limit_s          = 7200.0_dp
    wall_time_reserve_s        = 60.0_dp

    postprocess_interval_ms    = 1.0_dp
    field_save_interval_ms     = 1.0_dp
    checkpoint_interval_ms     = 5.0_dp
    save_spatial_fields        = .true.

    !--------------------------------------------------------------------------
    ! Read configuration. Namelist-group order in the file is irrelevant.
    !--------------------------------------------------------------------------
    config_file = 'setup_input.nml'
    arg_count = command_argument_count()
    if (arg_count >= 1) then
        call get_command_argument(1, config_file)
        if (len_trim(config_file) == 0) config_file = 'setup_input.nml'
    end if

    open(newunit=io_unit, file=trim(config_file), status='old', &
         action='read', iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) then
        write(*,'(A)') 'ERROR: cannot open configuration file: '//trim(config_file)
        write(*,'(A)') trim(iomsg)
        error stop 1
    end if

    rewind(io_unit)
    read(io_unit, nml=case_config, iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) call namelist_error('case_config', iomsg)

    rewind(io_unit)
    read(io_unit, nml=geometry_config, iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) call namelist_error('geometry_config', iomsg)

    rewind(io_unit)
    read(io_unit, nml=mixture_config, iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) call namelist_error('mixture_config', iomsg)

    rewind(io_unit)
    read(io_unit, nml=ignition_config, iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) call namelist_error('ignition_config', iomsg)

    rewind(io_unit)
    read(io_unit, nml=physics_config, iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) call namelist_error('physics_config', iomsg)

    rewind(io_unit)
    read(io_unit, nml=run_control_config, iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) call namelist_error('run_control_config', iomsg)

    rewind(io_unit)
    read(io_unit, nml=output_config, iostat=ierr, iomsg=iomsg)
    if (ierr /= 0) call namelist_error('output_config', iomsg)
    close(io_unit)

    call normalize_and_validate_configuration()
    call resolve_mechanism()
    call resolve_solver()

    ! Fresh-gas mole fractions.
    x_h2 = hydrogen_mole_percent/100.0_dp
    x_o2 = (1.0_dp-x_h2)/(1.0_dp+n2_o2_molar_ratio)
    x_n2 = n2_o2_molar_ratio*x_o2

    ! Equivalent old-interface stoichiometric notation:
    ! H2 + nu O2 + nu*(N2/O2) N2.
    nu  = (100.0_dp-hydrogen_mole_percent)/hydrogen_mole_percent / &
          (1.0_dp+n2_o2_molar_ratio)
    phi = 0.5_dp/nu

    cells_number_x = nint(domain_length_m/cell_size_m)
    realized_domain_length_m = real(cells_number_x,dp)*cell_size_m

    ignition_cells = nint(ignition_width_m/cell_size_m)
    realized_ignition_width_m = real(ignition_cells,dp)*cell_size_m

    !--------------------------------------------------------------------------
    ! Deterministic, strict case directory creation.
    !--------------------------------------------------------------------------
    work_dir = trim(results_root)//trim(fold_sep)//trim(campaign_id)// &
               trim(fold_sep)//trim(case_directory)

    call make_case_directory_strict(trim(results_root), trim(campaign_id), &
                                    trim(work_dir))
    call copy_task_setup(trim(work_dir))
    call copy_configuration(trim(config_file), trim(work_dir))
    call change_directory(trim(work_dir))

    !--------------------------------------------------------------------------
    ! Run lifetime is owned by run_control. For the trusted flame-outcome
    ! controller, wall_time is normally used as the safety ceiling.
    !--------------------------------------------------------------------------
    select case(trim(termination_mode))
    case('simulation_time')
        problem_run_control = run_control_c( &
            termination_mode = 'simulation_time', &
            final_time       = final_time_s)
    case('wall_time')
        problem_run_control = run_control_c( &
            termination_mode  = 'wall_time', &
            wall_time_limit   = wall_time_limit_s, &
            wall_time_reserve = wall_time_reserve_s)
    case('either')
        problem_run_control = run_control_c( &
            termination_mode  = 'either', &
            final_time        = final_time_s, &
            wall_time_limit   = wall_time_limit_s, &
            wall_time_reserve = wall_time_reserve_s)
    case default
        error stop 'ERROR: unsupported termination_mode after validation.'
    end select

    !--------------------------------------------------------------------------
    ! 1D planar / cylindrical / spherical domain.
    !--------------------------------------------------------------------------
    problem_domain = computational_domain_c( &
        dimensions        = 1, &
        cells_number      = (/cells_number_x,1,1/), &
        coordinate_system = trim(coordinate_system), &
        lengths           = reshape((/0.0_dp,0.0_dp,0.0_dp, &
                                      realized_domain_length_m,cell_size_m,cell_size_m/), &
                                    (/3,2/)), &
        axis_names        = (/'x','y','z'/))

    !--------------------------------------------------------------------------
    ! Chemistry and thermophysical properties.
    !--------------------------------------------------------------------------
    problem_chemistry = chemical_properties_c( &
        chemical_mechanism_file_name  = trim(mech_file), &
        default_enhanced_efficiencies = 1.0_dp, &
        E_act_units                   = 'cal.mol')

    problem_thermophysics = thermophysical_properties_c( &
        chemistry                   = problem_chemistry, &
        thermo_data_file_name       = trim(thermo_file), &
        transport_data_file_name    = trim(transdata_file), &
        molar_masses_data_file_name = 'molar_masses.dat')

    problem_mpi_support = mpi_communications_c(problem_domain)

    problem_solver_options = solver_options_c( &
        solver_name                  = trim(solver_name), &
        hydrodynamics_flag           = .true., &
        heat_transfer_flag           = .true., &
        molecular_diffusion_flag     = .true., &
        viscosity_flag               = .true., &
        thermal_radiation_flag       = thermal_radiation_enabled, &
        soret_diffusion_flag         = soret_diffusion_enabled, &
        chemical_reaction_flag       = .true., &
        grav_acc                     = (/0.0_dp,0.0_dp,0.0_dp/), &
        additional_particles_phases = 0, &
        CFL_flag                     = cfl_enabled, &
        CFL_coefficient              = cfl_coefficient, &
        initial_time_step            = initial_time_step)

    problem_data_manager = data_manager_c( &
        problem_domain, problem_mpi_support, problem_chemistry, &
        problem_thermophysics, problem_solver_options)

    call problem_data_manager%create_boundary_conditions( &
        problem_boundaries, number_of_boundary_types=2, default_boundary=1)
    call problem_data_manager%create_computational_mesh(problem_mesh)

    call problem_data_manager%create_scalar_field(p, 'pressure', 'p')
    call problem_data_manager%create_scalar_field(T, 'temperature', 'T')
    call problem_data_manager%create_scalar_field(rho, 'density', 'rho')
    call problem_data_manager%create_vector_field(v, 'velocity', 'v', 'spatial')
    call problem_data_manager%create_vector_field( &
        Y, 'specie_mass_fraction', 'Y', 'chemical')

    utter_loop = problem_domain%get_global_utter_cells_bounds()
    inner_loop = problem_domain%get_global_inner_cells_bounds()

    !--------------------------------------------------------------------------
    ! Resolve required species by name.
    !--------------------------------------------------------------------------
    h2_index  = problem_chemistry%get_chemical_specie_index('H2')
    o2_index  = problem_chemistry%get_chemical_specie_index('O2')
    n2_index  = problem_chemistry%get_chemical_specie_index('N2')
    h2o_index = problem_chemistry%get_chemical_specie_index('H2O')

    if (min(h2_index,o2_index,n2_index,h2o_index) <= 0) then
        error stop 'ERROR: selected mechanism must contain H2, O2, N2 and H2O.'
    end if

    !--------------------------------------------------------------------------
    ! Initial state.
    !
    ! Composition is authored in mole units and converted once over the complete
    ! field. Fresh gas is initialized everywhere first. The first exactly
    ! ignition_cells physical cells are then replaced by the inert hot mixture
    ! H2O + N2.
    !--------------------------------------------------------------------------
    T%cells(:,:,:) = initial_temperature
    p%cells(:,:,:) = initial_pressure

    do spec = 1, size(v%pr)
        v%pr(spec)%cells(:,:,:) = 0.0_dp
    end do

    do spec = 1, problem_chemistry%species_number
        Y%pr(spec)%cells(:,:,:) = 0.0_dp
    end do

    Y%pr(h2_index)%cells(:,:,:) = x_h2
    Y%pr(o2_index)%cells(:,:,:) = x_o2
    Y%pr(n2_index)%cells(:,:,:) = x_n2

    ignition_first_cell = inner_loop(1,1)
    ignition_last_cell  = ignition_first_cell + ignition_cells - 1

    if (ignition_last_cell > inner_loop(1,2)) then
        error stop 'ERROR: ignition zone extends beyond the physical domain.'
    end if

    do i = ignition_first_cell, ignition_last_cell
        T%cells(i,:,:) = ignition_temperature
        do spec = 1, problem_chemistry%species_number
            Y%pr(spec)%cells(i,:,:) = 0.0_dp
        end do
        Y%pr(h2o_index)%cells(i,:,:) = ignition_h2o_moles
        Y%pr(n2_index)%cells(i,:,:)  = ignition_n2_moles
    end do

    call problem_thermophysics%change_field_units_mole_to_dimless(Y)

    !--------------------------------------------------------------------------
    ! Boundary conditions.
    !
    ! At x=0 the same adiabatic slip-wall condition is used for all geometries.
    ! In cylindrical/spherical coordinates this is interpreted as the radial
    ! symmetry origin. The right boundary is a free outlet to the fresh gas.
    !--------------------------------------------------------------------------
    call problem_boundaries%create_boundary_type( &
        type_name               = 'wall', &
        slip                    = .true., &
        conductive              = .false., &
        wall_temperature        = 0.0_dp, &
        wall_conductivity_ratio = 0.0_dp, &
        priority                = 1)

    call problem_boundaries%create_boundary_type( &
        type_name               = 'outlet', &
        farfield_pressure       = initial_pressure, &
        farfield_temperature    = initial_temperature, &
        farfield_velocity       = 0.0_dp, &
        farfield_species_names  = [character(len=5) :: 'H2','O2','N2'], &
        farfield_concentrations = (/1.0_dp,nu,nu*n2_o2_molar_ratio/), &
        priority                = 2)

    problem_boundaries%bc_markers(utter_loop(1,1),:,:) = 1
    problem_boundaries%bc_markers(utter_loop(1,2),:,:) = 2

    !--------------------------------------------------------------------------
    ! Lightweight front / outcome history.
    !
    ! Operation 1 tracks min(dT/dx), appropriate because hot products are on the
    ! left and cold reactants on the right. Quadratic location refinement provides
    ! a subcell front coordinate. The updated postprocessor records the actual CFD
    ! sampling time in the configured output units.
    !
    ! Subsequent transducers at zero relative distance sample quantities at the
    ! current leading point. Domain maxima support extinction/stabilization
    ! classification without requiring high-frequency Tecplot output.
    !--------------------------------------------------------------------------
    observation_slice(:,1) = (/inner_loop(1,1),1,1/)
    observation_slice(:,2) = (/inner_loop(1,2),1,1/)

    operations_number = 5
    problem_post_proc_manager = post_processor_manager_c( &
        problem_data_manager, number_post_processors=1)

    call problem_post_proc_manager%create_post_processor( &
        problem_data_manager, post_processor_name='front_history', &
        operations_number=operations_number, &
        save_time=postprocess_interval_ms, save_time_units='milliseconds')

    ! 1. Temperature-gradient minimum and its location: primary front tracker.
    call problem_post_proc_manager%create_post_processor_operation( &
        problem_data_manager, 1, 'temperature', 'min_grad', &
        operation_area=observation_slice, grad_projection=1, &
        location_mode='quadratic')

    ! 2. Temperature at the tracked front.
    call problem_post_proc_manager%create_post_processor_operation( &
        problem_data_manager, 1, 'temperature', 'transducer', &
        operation_area_distance=(/0,0,0/))

    ! 3. H2 mass fraction at the tracked front.
    h2_field_name = 'specie_mass_fraction(H2)'
    call problem_post_proc_manager%create_post_processor_operation( &
        problem_data_manager, 1, trim(h2_field_name), 'transducer', &
        operation_area_distance=(/0,0,0/))

    ! 4. Maximum chemical-energy source in the physical domain. The computing
    !    module owns this derived field; the postprocessor definition stores its
    !    field name for resolution when the solver reconstructs the manager.
    call problem_post_proc_manager%create_post_processor_operation( &
        problem_data_manager, 1, 'energy_production_chemistry', 'max', &
        operation_area=observation_slice)

    ! 5. Maximum temperature in the physical domain.
    call problem_post_proc_manager%create_post_processor_operation( &
        problem_data_manager, 1, 'temperature', 'max', &
        operation_area=observation_slice)

    !--------------------------------------------------------------------------
    ! Spatial output. High-frequency physical termination uses front_history;
    ! Tecplot fields are intentionally much less frequent.
    !--------------------------------------------------------------------------
    if (save_spatial_fields) then
        effective_field_save_interval = field_save_interval_ms
    else
        effective_field_save_interval = 1.0e30_dp
    end if

    problem_data_save = data_save_c( &
        problem_data_manager, &
        visible_fields_names=[character(len=40) :: &
            'pressure', &
            'pressure_dynamic', &
            'temperature', &
            'density', &
            'velocity', &
            'specie_mass_fraction', &
            'velocity_of_sound', &
            'mixture_cp', &
            'thermal_conductivity', &
            'viscosity', &
            'energy_production_chemistry', &
            'energy_production_diffusion', &
            'energy_production_radiation'], &
        save_time        = effective_field_save_interval, &
        save_time_units  = 'milliseconds', &
        save_format      = 'tecplot', &
        data_save_folder = 'data_save', &
        debug_flag       = .false.)

    ! Restart serialization. run_control owns the actual lifetime.
    problem_data_io = data_io_c( &
        problem_data_manager, &
        check_time         = checkpoint_interval_ms, &
        check_time_units   = 'milliseconds', &
        data_output_folder = 'data_output')

    !--------------------------------------------------------------------------
    ! Human-readable metadata.
    !--------------------------------------------------------------------------
    open(newunit=log_unit, file=problem_setup_log_file, &
         status='replace', form='formatted', action='write')
    write(log_unit,'(A)') '1D H2-air flame propagation from wall/radial origin'
    write(log_unit,'(A,A)') 'Case ID: ', trim(case_id)
    write(log_unit,'(A,A)') 'Case fingerprint: ', trim(case_fingerprint)
    write(log_unit,'(A,A)') 'Case directory: ', trim(case_directory)
    write(log_unit,'(A,A)') 'Campaign ID: ', trim(campaign_id)
    write(log_unit,'(A,A)') 'Numerical variant: ', trim(numerical_variant)
    write(log_unit,'(A,A)') 'Coordinate system: ', trim(coordinate_system)
    write(log_unit,'(A,I0)') 'Computational cells: ', cells_number_x
    write(log_unit,'(A,ES14.6)') 'Cell size [m]: ', cell_size_m
    write(log_unit,'(A,ES14.6)') 'Domain length [m]: ', realized_domain_length_m
    write(log_unit,'(A,ES14.6)') 'Ignition width [m]: ', realized_ignition_width_m
    write(log_unit,'(A,ES14.6)') 'Fresh temperature [K]: ', initial_temperature
    write(log_unit,'(A,ES14.6)') 'Fresh pressure [Pa]: ', initial_pressure
    write(log_unit,'(A,F12.6)') 'H2 mole percent: ', hydrogen_mole_percent
    write(log_unit,'(A,F12.6)') 'Equivalence ratio: ', phi
    write(log_unit,'(A,A)') 'Chemical mechanism: ', trim(mechanism_name)
    write(log_unit,'(A,A)') 'Solver: ', trim(solver_name)
    write(log_unit,'(A,L1)') 'Thermal radiation: ', thermal_radiation_enabled
